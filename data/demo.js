/* ===================================================================
   demo.js — не часть сюжета. Маленькая сцена, которая на практике
   показывает всю v2-механику: доверие, флаги, инвентарь состояния,
   условное ветвление и выбор одной из нескольких концовок.

   Открой demo.html, пройди сцену дважды — один раз выбирая
   "Дружелюбно", другой раз "Холодно" — и посмотри, как меняется
   реакция Миры и какая концовка-заглушка сработает.

   В консоли браузера (F12) в любой момент доступно: state, resetState()
   =================================================================== */
const DEMO = [
  N('Это техническая демонстрация движка v2 (доверие/флаги/предметы), не часть сюжета «Последнего этажа».'),
  BG('bg_landing'),
  L('Мира','portrait_mira','— О, ты тут. Давно не виделись.'),
  EFFECT(()=>setFlag('MET_MIRA')),

  CHOICE('Как ответить Мире?', [
    { label:'Дружелюбно (+2 к доверию)', effect:()=>trustChange('MIRA', 2), lines:[
      L(PLAYER,'portrait_hero','— Привет! Рад тебя видеть.'),
      L('Мира','portrait_mira','— Взаимно. Давно тебя не было.'),
    ]},
    { label:'Холодно (−2 к доверию)', effect:()=>trustChange('MIRA', -2), lines:[
      L(PLAYER,'portrait_hero','— А, это ты.'),
      N('Мира прищуривается, но не уходит.'),
    ]},
  ]),

  // ветвление по накопленному доверию
  IF(s => s.trust.MIRA >= 2,
    [
      N('Мира явно расслабляется рядом с тобой.'),
      L('Мира','portrait_mira','— Слушай... покажу тебе кое-что. Только между нами.'),
    ],
    [
      N('Мира держится настороже, но всё же решается.'),
      L('Мира','portrait_mira','— Ладно, идём. Только не задавай лишних вопросов.'),
    ]
  ),

  ITEM('item_key','Мира протягивает старый ключ.'),
  GIVE_ITEM('KEY_OLD'),
  EVIDENCE_ADD(1),
  N('Ключ добавлен в состояние (KEY_OLD), EVIDENCE увеличен на 1. Это отдельная система от инвентаря-полоски в углу экрана — та про предметы сцены, эта про сюжетный прогресс между главами.'),

  // выбор одной из нескольких концовок по правилам — ровно то,
  // что в документе v2 определяет финалы A–E
  ROUTE([
    { check: s => s.trust.MIRA >= 2 && s.EVIDENCE >= 1,
      target: [ N('[Заглушка] Мира доверяет тебе, и у вас уже есть первая улика — это ветка в духе концовки A.') ] },
    { check: s => s.EVIDENCE >= 1,
      target: [ N('[Заглушка] Улика есть, но Мира держит дистанцию — это ближе к концовке C.') ] },
  ], [ N('[Заглушка] Пока не найдено ничего существенного.') ]),

  END(
    'ДЕМО ЗАВЕРШЕНА',
    'Открой консоль (F12) и введи <code>state</code> — увидишь итоговые значения.',
    'Чтобы пройти заново с чистого состояния: введи в консоли <code>resetState()</code> и перезагрузи страницу.'
  ),
];
